// Builds the Chrome version in dist/chrome from the same sources as the
// Firefox add-on (the repo root):
//   - manifest.chrome.json with the version from manifest.json
//   - sw.js, a service worker that importScripts() the Firefox background
//     scripts, so the list lives in one place
// Usage: node scripts/build.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "dist", "chrome");
const COPY = ["_locales", "icons", "lib", "content", "options", "popup", "background.js"];

const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, f), "utf8"));
const firefox = read("manifest.json");
const chrome = { ...read("manifest.chrome.json"), version: firefox.version };

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
for (const entry of COPY) {
  fs.cpSync(path.join(ROOT, entry), path.join(OUT, entry), {
    recursive: true,
    filter: (src) => !src.endsWith(".svg"),
  });
}

const scripts = firefox.background.scripts;
for (const s of scripts) {
  if (!fs.existsSync(path.join(OUT, s))) throw new Error(`background script ${s} missing from the Chrome build`);
}
fs.writeFileSync(
  path.join(OUT, "sw.js"),
  `// Generated by scripts/build.mjs from manifest.json background.scripts.\nimportScripts(\n${scripts.map((s) => `  ${JSON.stringify(s)}`).join(",\n")}\n);\n`
);
fs.writeFileSync(path.join(OUT, "manifest.json"), JSON.stringify(chrome, null, 2) + "\n");
console.log(`dist/chrome: version ${chrome.version}, ${scripts.length} background scripts`);
